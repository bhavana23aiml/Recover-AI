# =========================================================
# IN-MEMORY FALLBACK / TEST STORAGE
# =========================================================
#
# Supabase is now the persistent runtime store when:
#
#     RECOVERAI_PERSISTENCE_ENABLED=true
#
# These stores remain intentionally available for:
#
# - deterministic automated tests
# - Buildathon simulation fallback
# - temporary Supabase unavailability
#
# Before real external financial execution is enabled,
# persistence must become fail-closed rather than fallback.
# =========================================================

AUDIT_STORE: dict[str, list[AuditEvent]] = {}

IDEMPOTENCY_RESULT_STORE: dict[
    str,
    RecoveryExecutionResponse,
] = {}

IDEMPOTENCY_STATE: dict[str, str] = {}

STORE_LOCK = Lock()


# =========================================================
# SIMULATION CONFIGURATION
# =========================================================

RETRY_SUCCESS_PROBABILITY = {
    FailureCode.BANK_UNAVAILABLE: 0.72,
    FailureCode.NETWORK_ERROR: 0.82,
    FailureCode.PAYMENT_TIMEOUT: 0.68,
}


RETRY_ACTIONS = {
    "DELAYED_RETRY",
    "SHORT_RETRY",
    "VERIFY_THEN_RETRY",
}


# =========================================================
# CUSTOM EXCEPTION
# =========================================================

class RecoveryAlreadyInProgressError(RuntimeError):
    """
    Raised when an idempotent recovery attempt is already
    executing or previously entered an ambiguous error state.
    """

    pass


# =========================================================
# PERSISTENCE CONFIGURATION
# =========================================================

def persistence_enabled() -> bool:
    value = os.getenv(
        "RECOVERAI_PERSISTENCE_ENABLED",
        "false",
    )

    return value.strip().lower() in {
        "1",
        "true",
        "yes",
        "on",
    }


def _persistence_warning(operation: str, exc: Exception) -> None:
    """
    Do not print secrets or raw database payloads.

    During the current SIMULATION phase RecoverAI can safely
    fall back to memory if Supabase is unavailable.
    """
    print(
        "[RecoverAI] Supabase persistence unavailable during "
        f"{operation}. Using simulation fallback. "
        f"Error type: {type(exc).__name__}"
    )


# =========================================================
# AUDIT HELPERS
